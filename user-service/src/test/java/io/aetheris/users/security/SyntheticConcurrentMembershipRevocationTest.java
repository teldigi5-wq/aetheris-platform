package io.aetheris.users.security;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.JwtException;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.security.Keys;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.security.SecureRandom;
import java.time.Instant;
import java.util.Date;
import java.util.List;
import javax.crypto.SecretKey;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Disposable PostgreSQL concurrency witness, NOT production authorization.
 *
 * PostgreSQL READ COMMITTED observes committed revocations on the next SQL
 * statement. REPEATABLE READ retains its earlier MVCC snapshot, even though
 * statement_timestamp() advances. The SAME throwaway signed JWT is verified
 * across both revoke transactions; no live Identity token or cache is involved.
 *
 * This opt-in test is invoked ONLY within the synthetic three-role CI lab.
 * Both passwords are generated by that lab, never stored in the repository.
 */
@EnabledIfSystemProperty(named = "aetheris.membership.concurrent.synthetic", matches = "true")
class SyntheticConcurrentMembershipRevocationTest {
    private static final String SYNTHETIC_URL =
        "jdbc:postgresql://127.0.0.1:55436/shared_synthetic?currentSchema=user_stage";
    private static final String TENANT_A = "11111111-1111-4111-8111-111111111111";
    private static final String ISSUER = "https://identity.aetheris.example.invalid";
    private static final String AUDIENCE = "aetheris-user-api";
    private static final SecretKey SIGNER = randomTestKey();
    private static final SecretKey FOREIGN_SIGNER = randomTestKey();

    private static SecretKey randomTestKey() {
        byte[] material = new byte[32];
        new SecureRandom().nextBytes(material);
        return Keys.hmacShaKeyFor(material);
    }

    private static String syntheticToken(SecretKey signer, long uid,
                                         String tenant, String audience) {
        Instant now = Instant.now();
        return Jwts.builder()
            .subject("synthetic-revocation@example.invalid")
            .claim("uid", uid)
            .claim("tenant_id", tenant)
            .claim("role", "API_CONSUMER")
            .claim("scopes", List.of("users:read"))
            .issuer(ISSUER)
            .claim("aud", List.of(audience))
            .issuedAt(Date.from(now.minusSeconds(10)))
            .expiration(Date.from(now.plusSeconds(300)))
            .signWith(signer).compact();
    }

    /**
     * Synthetic-only signed-principal authorization probe. A good signature
     * is NOT enough: each call must independently check the exact object and
     * fresh tenant membership via the restricted PostgreSQL runtime role.
     * The claimed tenant is only a selector, never a membership grant.
     */
    private static boolean admitsSignedObject(Connection reader, String signed,
                                               long objectId) throws SQLException {
        if (signed == null || objectId <= 0) return false;
        try {
            Claims claims = Jwts.parser().verifyWith(SIGNER).build()
                .parseSignedClaims(signed).getPayload();
            Object rawUid = claims.get("uid");
            if (!(rawUid instanceof Long || rawUid instanceof Integer)) return false;
            long uid = ((Number) rawUid).longValue();
            String assertedTenant = claims.get("tenant_id", String.class);
            Object rawScopes = claims.get("scopes");
            if (uid <= 0 || !TENANT_A.equals(assertedTenant)
                || !ISSUER.equals(claims.getIssuer())
                || claims.getAudience() == null || claims.getAudience().size() != 1
                || !claims.getAudience().contains(AUDIENCE)
                || !"API_CONSUMER".equals(claims.get("role", String.class))
                || !(rawScopes instanceof List<?> scopes)
                || !scopes.equals(List.of("users:read"))
                || claims.getSubject() == null || claims.getSubject().isBlank()
                || claims.getIssuedAt() == null || claims.getExpiration() == null
                || !claims.getExpiration().after(claims.getIssuedAt())) return false;
            return hasGrant(reader, uid, objectId);
        } catch (JwtException | IllegalArgumentException invalid) {
            return false;
        }
    }
    private static final String CHECK_GRANT = """
        SELECT EXISTS (
          SELECT 1
          FROM user_stage.synthetic_user_owner_bindings b
          JOIN user_stage.synthetic_identity_tenant_memberships m
            ON m.identity_uid = b.identity_uid AND m.tenant_id = b.tenant_id
          WHERE b.identity_uid = ?
            AND b.user_id = ?
            AND b.tenant_id = ?::uuid
            AND m.revoked_at IS NULL
            AND m.expires_at > statement_timestamp()
        )
        """;

    private static String requiredSyntheticPassword(String name) {
        if (!"yes".equals(System.getenv("AETHERIS_THREE_ROLE_SYNTHETIC_ONLY"))) {
            throw new IllegalStateException("Disposable three-role lab opt-in missing");
        }
        String password = System.getenv(name);
        if (password == null || password.length() < 32) {
            throw new IllegalStateException("Required disposable role credentials missing");
        }
        return password;
    }

    private static Connection connect(String role, String secretEnv) throws SQLException {
        return DriverManager.getConnection(SYNTHETIC_URL, role,
            requiredSyntheticPassword(secretEnv));
    }

    private static String scalar(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet results = statement.executeQuery(sql)) {
            assertTrue(results.next(), "Expected a single synthetic fixture result");
            return results.getString(1);
        }
    }

    private static long userId(Connection reader, String email) throws SQLException {
        try (PreparedStatement statement = reader.prepareStatement(
                "SELECT id FROM user_stage.users WHERE email = ?")) {
            statement.setString(1, email);
            try (ResultSet results = statement.executeQuery()) {
                assertTrue(results.next(), "Missing synthetic user fixture");
                return results.getLong(1);
            }
        }
    }

    private static boolean hasGrant(Connection reader, long uid, long objectId)
            throws SQLException {
        try (PreparedStatement statement = reader.prepareStatement(CHECK_GRANT)) {
            statement.setLong(1, uid);
            statement.setLong(2, objectId);
            statement.setString(3, TENANT_A);
            try (ResultSet result = statement.executeQuery()) {
                assertTrue(result.next(), "Missing synthetic grant decision");
                return result.getBoolean(1);
            }
        }
    }

    private static void changeRevocation(Connection writer, long uid, boolean revoke)
            throws SQLException {
        String sql = revoke
            ? """
              UPDATE user_stage.synthetic_identity_tenant_memberships
                 SET revoked_at = statement_timestamp()
               WHERE identity_uid = ? AND tenant_id = ?::uuid
                 AND revoked_at IS NULL
              """
            : """
              UPDATE user_stage.synthetic_identity_tenant_memberships
                 SET revoked_at = NULL
               WHERE identity_uid = ? AND tenant_id = ?::uuid
                 AND revoked_at IS NOT NULL
              """;
        try (PreparedStatement statement = writer.prepareStatement(sql)) {
            statement.setLong(1, uid);
            statement.setString(2, TENANT_A);
            assertEquals(1, statement.executeUpdate(),
                "Synthetic membership must have exactly one controlled transition");
        }
        writer.commit();
    }

    @Test
    void readCommittedSeesCommittedRevocationWhileRepeatableReadCanRemainStale()
            throws Exception {
        try (Connection reader = connect("user_runtime",
                    "AETHERIS_SYNTHETIC_USER_RUNTIME_PASSWORD");
             Connection writer = connect("user_migrator",
                    "AETHERIS_SYNTHETIC_USER_MIGRATOR_PASSWORD")) {
            assertEquals("shared_synthetic", scalar(reader, "SELECT current_database()"));
            assertEquals("user_runtime", scalar(reader, "SELECT current_user"));
            assertEquals("user_migrator", scalar(writer, "SELECT current_user"));

            long objectId = userId(reader, "user-role@example.invalid");
            long identityUid = userId(reader, "user-two-role@example.invalid");
            // Construct ONCE; do not re-sign after a revoke or renewal. A
            // previously valid bearer must not retain an old grant.
            String sameSignedToken = syntheticToken(SIGNER, identityUid, TENANT_A, AUDIENCE);
            assertFalse(admitsSignedObject(reader,
                syntheticToken(FOREIGN_SIGNER, identityUid, TENANT_A, AUDIENCE), objectId),
                "A forged signer may never reach the membership read");
            assertFalse(admitsSignedObject(reader,
                syntheticToken(SIGNER, identityUid, TENANT_A, "another-audience"), objectId),
                "A token for another backend may never grant access");
            assertFalse(admitsSignedObject(reader,
                syntheticToken(SIGNER, identityUid, "22222222-2222-4222-8222-222222222222", AUDIENCE), objectId),
                "A signed tenant assertion cannot create an object grant");
            assertFalse(admitsSignedObject(reader,
                syntheticToken(SIGNER, objectId, TENANT_A, AUDIENCE), objectId),
                "Matching the unrelated resource ID does not prove identity ownership");
            reader.setTransactionIsolation(Connection.TRANSACTION_READ_COMMITTED);
            reader.setAutoCommit(false);
            writer.setAutoCommit(false);
            boolean syntheticMembershipChanged = false;
            try {
                assertTrue(admitsSignedObject(reader, sameSignedToken, objectId),
                    "Synthetic Tenant A must be active at this rehearsal checkpoint");

                // Both transactions overlap: the migrator commits its revocation
                // while the runtime read transaction remains open.
                changeRevocation(writer, identityUid, true);
                syntheticMembershipChanged = true;
                assertFalse(admitsSignedObject(reader, sameSignedToken, objectId),
                    "The SAME previously admitted JWT must be denied after revocation; READ COMMITTED must deny on a new statement after revoke commit");
                reader.rollback();

                changeRevocation(writer, identityUid, false);
                syntheticMembershipChanged = false;

                reader.setTransactionIsolation(Connection.TRANSACTION_REPEATABLE_READ);
                assertTrue(admitsSignedObject(reader, sameSignedToken, objectId),
                    "REPEATABLE READ must establish an active membership snapshot");
                changeRevocation(writer, identityUid, true);
                syntheticMembershipChanged = true;
                assertTrue(admitsSignedObject(reader, sameSignedToken, objectId),
                    "REPEATABLE READ demonstrates stale MVCC visibility; do not use for fresh authorization");

                // End the stale snapshot. A new READ COMMITTED transaction must
                // no longer grant the revoked identity/object tuple.
                reader.rollback();
                reader.setTransactionIsolation(Connection.TRANSACTION_READ_COMMITTED);
                assertFalse(admitsSignedObject(reader, sameSignedToken, objectId),
                    "New transaction must observe committed revocation");
                reader.rollback();
            } finally {
                reader.rollback();
                writer.rollback();
                if (syntheticMembershipChanged) {
                    // Restore the disposable fixture so the existing lifecycle
                    // rehearsal can independently revoke Tenant A afterward.
                    changeRevocation(writer, identityUid, false);
                }
            }
        }
    }
}
