#!/usr/bin/env bash
# Execute additive SQL twice against a throwaway, separate Postgres database.
# Never connects to an existing Aetheris production database.
set -euo pipefail
: "${RUNNER_TEMP:?Hosted CI runner required}"
: "${XERJ_COMPOSE_PROJECT:?Dedicated disposable Compose namespace required}"
[[ "$XERJ_COMPOSE_PROJECT" == xerj-mtls-ci-* ]] || exit 2

compose=(docker compose -p "$XERJ_COMPOSE_PROJECT" -f tests/security/xerj-disposable-deps.compose.yml)
psql() {
  "${compose[@]}" exec -T postgres psql -X -v ON_ERROR_STOP=1 -U xerj_ci "$@"
}
psql -d postgres -c 'CREATE DATABASE xerj_tenant_migration_smoke' >/dev/null
psql -d xerj_tenant_migration_smoke <<'SQL' >/dev/null
CREATE TABLE identity_accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  email varchar(180) NOT NULL UNIQUE,
  password_hash varchar(100) NOT NULL,
  role varchar(32) NOT NULL
);
CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255),
  email varchar(255) NOT NULL UNIQUE
);
INSERT INTO identity_accounts(name,email,password_hash,role)
VALUES ('Legacy synthetic identity','historical@example.test','synthetic-test-hash','API_CONSUMER');
INSERT INTO users(name,email)
VALUES ('Legacy synthetic record','historical-user@example.test');
SQL
for repeat in 1 2; do
  psql -d xerj_tenant_migration_smoke -f - \
    < docs/security/migrations/20261106_01_identity_account_tenant.sql >/dev/null
  psql -d xerj_tenant_migration_smoke -f - \
    < docs/security/migrations/20261106_02_user_record_tenant.sql >/dev/null
done
result="$(psql -d xerj_tenant_migration_smoke -t -A -c "
SELECT (
  (SELECT count(*) FROM identity_accounts WHERE tenant_id IS NULL)=1
  AND (SELECT count(*) FROM users WHERE tenant_id IS NULL)=1
  AND EXISTS (SELECT 1 FROM pg_indexes WHERE indexname='ix_identity_accounts_tenant_id')
  AND EXISTS (SELECT 1 FROM pg_indexes WHERE indexname='ix_users_tenant_id_id')
)::text
" 2>/dev/null)"
test "$result" = "true" || { echo "XERJ_TENANT_LEGACY_ROW_OR_MIGRATION_GUARD_FAILED"; exit 1; }
echo "XERJ_TENANT_POSTGRES_ADDITIVE_IDEMPOTENT_MIGRATION_PASS legacy_rows_unassigned=2 runs=2"
