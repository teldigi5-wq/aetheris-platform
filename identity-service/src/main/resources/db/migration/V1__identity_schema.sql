-- Identity Service schema (owned exclusively by this service; see application.yml flyway).
-- Mirrors the JPA mappings validated by Hibernate (ddl-auto: validate).
CREATE TABLE identity.identity_accounts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(180) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(32)  NOT NULL,
    CONSTRAINT uk_identity_accounts_email UNIQUE (email)
);

CREATE TABLE identity.identity_refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT      NOT NULL REFERENCES identity.identity_accounts (id),
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT idx_refresh_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_identity_refresh_tokens_account ON identity.identity_refresh_tokens (account_id);
