-- SYNTHETIC FRESH DATABASE REHEARSAL ONLY. Not an application migration.
-- Do not apply to an existing PostgreSQL database or to production.
CREATE TABLE identity_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(32) NOT NULL,
    CONSTRAINT uk_identity_accounts_email UNIQUE (email)
);

CREATE TABLE identity_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_identity_refresh_account
        FOREIGN KEY (account_id) REFERENCES identity_accounts (id),
    CONSTRAINT uk_identity_refresh_token_hash UNIQUE (token_hash)
);

-- Explicit index from RefreshToken @Table(indexes=...), in addition to
-- its unique @Column constraint. Review redundancy before production migration.
CREATE UNIQUE INDEX idx_refresh_token_hash ON identity_refresh_tokens (token_hash);
