-- Candidate only. NOT auto-executed by services or permitted on an existing database.
-- Identity Service: first migration for a NEW empty Postgres 16 database.
-- Existing Hibernate-managed schemas require separately approved baseline mapping.
CREATE TABLE identity_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(32) NOT NULL,
    CONSTRAINT uk_identity_accounts_email UNIQUE (email)
);

CREATE TABLE identity_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES identity_accounts(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX idx_refresh_token_hash ON identity_refresh_tokens(token_hash);
